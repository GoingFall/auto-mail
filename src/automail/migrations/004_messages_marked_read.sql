-- 004: 记录「由程序标记为已读」的时间
--
-- 背景：v1 全程只读邮箱（EXAMINE + BODY.PEEK），不改变任何邮件状态。新增的
-- 已读回写是本项目**第一个对邮箱的写操作**，因此需要可审计的痕迹：
--
--   * 知道自己改写过了什么（排查「邮件怎么变已读了」时不必靠猜）
--   * 幂等：已标记过的不再重复 STORE，省一次往返
--   * 可回退：明确知道哪些是本程序标记的，回退时不会误碰用户自己读过的邮件
--
-- 为 NULL 表示「本程序未标记过」。注意它与 flags 里的 \Seen 语义不同：
-- \Seen 可能是用户在别的客户端里读的，而这一列只记我们自己的动作。

ALTER TABLE messages ADD COLUMN marked_read_at TEXT;
